def _render_card(rank: int, opp: dict[str, Any]) -> str:
    watch = opp.get("momentum_watch", False)
    watch_badge = (
        '<span style="font-size:10px;color:#ff6b35;background:#2a1810;padding:2px 6px;border-radius:3px;margin-left:8px;letter-spacing:1px;">🔁 MOMENTUM</span>'
        if watch
        else ""
    )

    evidence = opp.get("evidence", []) or []
    evidence_html = "\n".join(
        f'<li style="margin-bottom:6px;">{e}</li>' for e in evidence
    )

    sources = opp.get("source_videos", []) or []
    source_html = "  ".join(
        f'<a href="{s}" style="color:#888;text-decoration:underline;margin-right:8px;">link {i+1}</a>'
        for i, s in enumerate(sources[:3])
    )

    return _CARD_TEMPLATE.format(
        rank=rank,
        title=_escape_html(opp.get("title", "Untitled")),
        signal=opp.get("signal_strength", "?"),
        category=_escape_html(opp.get("category", "—")),
        price_band=_escape_html(opp.get("price_band", "?")),
        why_now=_escape_html(opp.get("why_now", "")),
        evidence_items=evidence_html,
        action=_escape_html(opp.get("recommended_action", "—")),
        source_links=source_html or '<span style="color:#444;">no source links</span>',
        watch_badge=watch_badge,
    )


def _escape_html(text: Any) -> str:
    """Minimal HTML escape — we trust our own briefing text but defensively encode."""
    if not isinstance(text, str):
        text = str(text)
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def render_briefing_html(
    category: str,
    country: str,
    opportunities: list[dict[str, Any]],
    actor_url: str = "https://apify.com",
) -> str:
    """Render the full HTML email body."""
    today = datetime.now(timezone.utc).strftime("%a %b %d, %Y")
    cards = "\n".join(_render_card(i + 1, opp) for i, opp in enumerate(opportunities))
    return _HTML_TEMPLATE.format(
        date=today,
        category=_escape_html(category),
        country=_escape_html(country),
        count=len(opportunities),
        cards=cards or "<tr><td>(no opportunities surfaced today)</td></tr>",
        actor_url=actor_url,
    )


# ============================================================================
# Sending
# ============================================================================


async def send_briefing_email(
    category: str,
    country: str,
    opportunities: list[dict[str, Any]],
    log: Any,
    actor_url: str = "https://apify.com",
) -> bool:
    """Send the briefing as an HTML email via Resend.

    Returns True if sent, False if skipped or failed. Never raises — email
    is a nice-to-have, the briefing already lives in Apify KV/Dataset.
    """
    api_key = os.environ.get("RESEND_API_KEY")
    to_email = os.environ.get("TRENDSTRIKE_EMAIL_TO")
    from_email = os.environ.get("TRENDSTRIKE_EMAIL_FROM", "onboarding@resend.dev")

    if not api_key:
        log.info("[email] RESEND_API_KEY not set — skipping email delivery")
        return False
    if not to_email:
        log.info("[email] TRENDSTRIKE_EMAIL_TO not set — skipping email delivery")
        return False

    resend.api_key = api_key
    today = datetime.now(timezone.utc).strftime("%a %b %d")
    top_pick = opportunities[0]["title"] if opportunities else "no opportunities"
    subject = f"📊 TrendStrike — {today} — {top_pick}"

    html = render_briefing_html(category, country, opportunities, actor_url)

    try:
        result = resend.Emails.send(
            {
                "from": f"TrendStrike <{from_email}>",
                "to": [to_email],
                "subject": subject,
                "html": html,
            }
        )
        log.info("[email] sent to %s (id=%s)", to_email, result.get("id", "?"))
        return True
    except Exception as e:
        log.warning("[email] send failed: %s", e)
        return False
