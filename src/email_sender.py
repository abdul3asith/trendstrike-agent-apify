"""
Email delivery for TrendStrike briefings.

Sends the briefing as a polished HTML email via Resend. Designed to look
like a real morning newsletter a TikTok Shop seller would actually open —
not raw markdown dumped into a <pre> tag.

Failure mode: if Resend is unreachable or the API key is missing, we log
and continue. Email is a nice-to-have delivery channel; the briefing is
already saved in the Apify KV store and pushed to the Dataset regardless.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from typing import Any

import resend

# ============================================================================
# HTML rendering
# ============================================================================

# Email-safe CSS: inline styles, no flexbox grid, table-friendly. We use a
# single dark-mode card stack because every modern email client (Gmail,
# Apple Mail, Outlook) renders this reliably.

